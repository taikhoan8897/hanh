-- SQL Script cập nhật các cột thông tin phần cứng trong ComputerAssets
-- Chạy script này trên SQL Server để cập nhật schema

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'ComputerAssets' AND COLUMN_NAME = 'RamInfo')
BEGIN
    ALTER TABLE ComputerAssets ADD RamInfo NVARCHAR(50);
END

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'ComputerAssets' AND COLUMN_NAME = 'CpuInfo')
BEGIN
    ALTER TABLE ComputerAssets ADD CpuInfo NVARCHAR(255);
END

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'ComputerAssets' AND COLUMN_NAME = 'DiskInfo')
BEGIN
    ALTER TABLE ComputerAssets ADD DiskInfo NVARCHAR(255);
END
ELSE
BEGIN
    ALTER TABLE ComputerAssets ALTER COLUMN DiskInfo NVARCHAR(255);
END

-- Thêm các cột khác nếu chưa có
IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'ComputerAssets' AND COLUMN_NAME = 'Hostname')
BEGIN
    ALTER TABLE ComputerAssets ADD Hostname NVARCHAR(255);
END

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'ComputerAssets' AND COLUMN_NAME = 'WindowsUser')
BEGIN
    ALTER TABLE ComputerAssets ADD WindowsUser NVARCHAR(255);
END

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'ComputerAssets' AND COLUMN_NAME = 'IpAddress')
BEGIN
    ALTER TABLE ComputerAssets ADD IpAddress NVARCHAR(50);
END
